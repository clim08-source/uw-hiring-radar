// Picks the database for this environment and prepares the Prisma client.
//
//   No DATABASE_URL (local default) → SQLite file at prisma/dev.db, zero config.
//   DATABASE_URL=postgres://…       → Postgres (needed on Vercel and other serverless hosts,
//                                     whose filesystem is read-only and not shared).
//
// Prisma fixes the provider in the schema file, so for Postgres this writes a copy of
// prisma/schema.prisma with the datasource swapped, and generates the client from that.
//
//   node scripts/prepare-db.mjs          generate the client
//   node scripts/prepare-db.mjs --push   also create / update the tables

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const push = process.argv.includes("--push");
const env = process.env;

// Vercel's Neon / Postgres integrations expose these names.
const urlVar = ["DATABASE_URL", "POSTGRES_PRISMA_URL", "POSTGRES_URL"].find((name) => /^postgres(ql)?:\/\//.test(env[name] ?? ""));
const directVar = ["DATABASE_URL_UNPOOLED", "POSTGRES_URL_NON_POOLING"].find((name) => /^postgres(ql)?:\/\//.test(env[name] ?? ""));

const run = (cmd) => execSync(cmd, { stdio: "inherit" });

if (urlVar) {
  const base = readFileSync("prisma/schema.prisma", "utf8");
  const datasource = `datasource db {\n  provider  = "postgresql"\n  url       = env("${urlVar}")${directVar ? `\n  directUrl = env("${directVar}")` : ""}\n}`;
  const swapped = base.replace(/datasource db \{[^}]*\}/, datasource);
  if (swapped === base) throw new Error("Could not find the datasource block in prisma/schema.prisma");
  writeFileSync("prisma/schema.postgres.prisma", `// GENERATED by scripts/prepare-db.mjs from schema.prisma — do not edit.\n${swapped}`);
  console.log(`[prepare-db] Using Postgres from ${urlVar}`);
  if (push) run("npx prisma db push --schema prisma/schema.postgres.prisma --skip-generate");
  run("npx prisma generate --schema prisma/schema.postgres.prisma");
} else {
  if (env.VERCEL) {
    console.warn(
      "\n[prepare-db] WARNING: no Postgres DATABASE_URL is set. SQLite cannot work on Vercel, so every API route will fail.\n" +
        "             Add a Postgres database (Vercel → Storage → Neon) and redeploy.\n",
    );
  } else {
    console.log("[prepare-db] Using local SQLite (prisma/dev.db)");
    if (push) run("npx prisma db push --skip-generate");
  }
  run("npx prisma generate");
}
